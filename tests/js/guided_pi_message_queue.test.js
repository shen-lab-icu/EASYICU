'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
require(path.resolve('tests/js/guided_pi_module_harness.cjs'));
global.window = {};
require(path.resolve(process.argv[2]));
const owner = window.EasyICU.guidedPi.require('messageQueue');
const escaped = value => String(value).replace(/</g, '&lt;').replace(/"/g, '&quot;');
const html = owner.render({ items: [{ id: 'q1', status: 'queued', message: '<script>bad</script>' }] }, { tr: (en) => en, esc: escaped });
assert.ok(html.includes('data-gpi-cancel-followup="q1"'));
assert.ok(!html.includes('<script>'));
assert.ok(html.includes('Queued for the next reply'));
(async () => {
  let resolve;
  let calls = 0;
  const state = { host: null, session: { session_id: 's' }, draft: 'question', busy: true };
  const api = { sendPiCopilotMessage: async () => { calls += 1; return new Promise(done => { resolve = done; }); } };
  const queue = owner.create({ state, api: () => api, projectId: () => 'p', render() {}, refreshSession: async () => {}, watchJob() {}, errorText: error => error.message });
  const first = queue.send('question');
  const second = queue.send('question');
  assert.equal(calls, 1, 'double clicks submit only once');
  await second;
  assert.equal(state.queueSubmitting, true);
  state.draft = 'next thought';
  resolve({ status: 'queued', queue: { items: [] } });
  await first;
  assert.equal(state.draft, 'next thought', 'typing during submission is preserved');
  assert.equal(state.queueSubmitting, false);
  queue.stop();
  let reject;
  api.cancelPiCopilotFollowup = () => new Promise((_, fail) => { reject = fail; });
  const cancellation = queue.cancel('q1');
  state.session = { session_id: 'different' };
  reject(new Error('late failure'));
  await cancellation;
  assert.equal(state.error, undefined, 'late errors do not overwrite another conversation');
  state.host = {};
  state.session = { session_id: 's' };
  state.busy = false;
  const watched = [];
  let refreshed = 0;
  api.loadPiCopilotFollowups = async () => ({ queue: { items: [
    { id: 'submitted', status: 'submitted', job_id: 'fresh-turn' },
  ] } });
  api.loadJobSnapshot = async () => ({ status: 'running' });
  const resumed = owner.create({ state, api: () => api, projectId: () => 'p', render() {},
    refreshSession: async () => { refreshed += 1; }, watchJob: id => watched.push(id), errorText: error => error.message });
  await resumed.reconcile();
  assert.deepEqual(watched, ['fresh-turn'], 'a delivered follow-up attaches to its own job');
  assert.equal(state.jobId, 'fresh-turn');
  assert.equal(state.busy, true);
  await resumed.reconcile();
  assert.equal(refreshed, 1, 'submitted turns are attached only once');
  resumed.stop();
  let resolveLate;
  api.loadPiCopilotFollowups = () => new Promise(done => { resolveLate = done; });
  const late = resumed.reconcile();
  state.session = { session_id: 'another-session' };
  resolveLate({ queue: { items: [{ id: 'stale', status: 'queued' }] } });
  await late;
  assert.equal(state.session.followup_queue, undefined, 'late queue snapshots cannot cross conversations');
  resumed.stop();
  console.log('message queue contracts passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
