"""Generate and verify schema-faithful, non-patient converted ICU sources.

Run ``python -m easyicu.synthetic_sources hirid /new/fixture/directory``.
Verification compares with locally regenerated bytes, never a caller's claim
or self-supplied checksum. No database credentials, downloads or real inputs.
"""

from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path

from easyicu.synthetic_source_tables import DATABASES, source_tables
from easyicu.synthetic_source_values import SEED

MANIFEST = "synthetic_source.json"
VERSION = "easyicu.synthetic_source/1"
NOTICE = "SYNTHETIC TEST DATA — no patient data; results are not clinical findings."


def _parameters(database, stays):
    if database not in DATABASES or type(stays) is not int or not 3 <= stays <= 600:
        raise ValueError("Expected hirid, aumc or sic and 3–600 synthetic stays (default 400).")


def _members(database, stays):
    import pyarrow as pa
    import pyarrow.parquet as pq

    for relative, table in source_tables(database, stays):
        buffer = pa.BufferOutputStream()
        pq.write_table(table, buffer, compression="snappy", version="2.6")
        yield relative, buffer.getvalue().to_pybytes(), table.num_rows


def _manifest(database, stays, files):
    return {"schema_version": VERSION, "source_kind": "synthetic", "database": database,
            "contains_patient_data": False, "seed": SEED, "stays": stays,
            "notice": NOTICE, "files": files}


@lru_cache(maxsize=8)
def _expected_manifest(database, stays):
    return _manifest(database, stays, {
        name: {"sha256": hashlib.sha256(payload).hexdigest(), "size_bytes": len(payload), "rows": rows}
        for name, payload, rows in _members(database, stays)
    })


def generate_source(destination: str | Path, database: str, *, stays: int = 400) -> dict:
    """Write a new converted source; refuse existing paths, including empty directories."""
    _parameters(database, stays)
    root = Path(destination).absolute()
    if root.resolve() != root:
        raise ValueError("Synthetic source paths must not traverse symlinks.")
    root.mkdir(parents=True, exist_ok=False)
    files = {}
    for relative, payload, rows in _members(database, stays):
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
        files[relative] = {"sha256": hashlib.sha256(payload).hexdigest(),
                           "size_bytes": len(payload), "rows": rows}
    manifest = _manifest(database, stays, files)
    (root / "README.md").write_text(NOTICE + "\n", encoding="utf-8")
    (root / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def verify_source(source: str | Path) -> dict | None:
    """Return verified provenance; edited, forged or mixed sources get no exemption."""
    root = Path(source).absolute()
    marker = root / MANIFEST
    try:
        if root.resolve() != root or marker.is_symlink() or not marker.is_file():
            return None
        if marker.stat().st_size > 128 * 1024:
            return None
        manifest = json.loads(marker.read_text(encoding="utf-8"))
        database, stays = manifest["database"], manifest["stays"]
        _parameters(database, stays)
        expected = _expected_manifest(database, stays)
        if manifest != expected:
            return None
        files = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() or p.is_symlink()}
        if files != {*expected["files"], MANIFEST, "README.md"}:
            return None
        readme = root / "README.md"
        if readme.is_symlink() or readme.read_bytes() != (NOTICE + "\n").encode():
            return None
        for relative, receipt in expected["files"].items():
            member = root / relative
            if member.resolve() != member or member.stat().st_size != receipt["size_bytes"]:
                return None
            if hashlib.sha256(member.read_bytes()).hexdigest() != receipt["sha256"]:
                return None
        return manifest
    except (OSError, ValueError, TypeError, KeyError):
        return None


def main():
    import argparse

    parser = argparse.ArgumentParser(description=NOTICE)
    parser.add_argument("database", choices=DATABASES)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--stays", type=int, default=400)
    args = parser.parse_args()
    manifest = generate_source(args.destination, args.database, stays=args.stays)
    print(json.dumps({k: v for k, v in manifest.items() if k != "files"}, indent=2))


if __name__ == "__main__":
    main()
